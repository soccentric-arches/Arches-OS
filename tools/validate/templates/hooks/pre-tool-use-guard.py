#!/usr/bin/env python3
"""PreToolUse hook — deterministic enforcement of the meta-arches-rules skill.

Guidance in CLAUDE.md / the meta-arches-rules skill only *guides* the model.
This hook *enforces* the two rules that have already cost this repo its git
origin once (see CLAUDE.md history):

  1. Never hand-edit layers/ (the kas checkout tree). It is regenerated by
     kas on every `make build` and upstream layers are never patched.
  2. Never add a git submodule / gitlink under layers/. Orphan gitlinks with
     no .gitmodules previously made kas clone a repo at the workspace root
     and overwrite this repo's .git.

It also asks for confirmation (rather than silently running) on a short list
of destructive shell commands, mirroring the operational-safety rules already
in effect for this workspace.

Reads a PreToolUse JSON payload on stdin and writes a decision to stdout.
See: https://code.visualstudio.com/docs/agents/reference/hooks-reference
"""
import json
import re
import sys

PATH_KEYS = {"filePath", "file_path", "path"}


def decide(permission, reason):
    print(json.dumps({
        "hookSpecificOutput": {
            "hookEventName": "PreToolUse",
            "permissionDecision": permission,
            "permissionDecisionReason": reason,
        }
    }))
    sys.exit(0)


def allow():
    print(json.dumps({"continue": True}))
    sys.exit(0)


def find_paths(obj):
    """Recursively collect string values under keys that name a file path,
    including nested 'replacements' arrays (multi_replace_string_in_file) and
    'files' arrays. Deliberately narrow: does not scan free-text fields like
    content/command/explanation, to avoid false positives on unrelated edits
    that merely mention a path in a string.
    """
    found = []
    if isinstance(obj, dict):
        for key, value in obj.items():
            if key in PATH_KEYS and isinstance(value, str):
                found.append(value)
            elif key == "files" and isinstance(value, list):
                found.extend(v for v in value if isinstance(v, str))
            else:
                found.extend(find_paths(value))
    elif isinstance(obj, list):
        for item in obj:
            found.extend(find_paths(item))
    return found


try:
    payload = json.load(sys.stdin)
except Exception:
    # Malformed input must never block the agent; fail open.
    allow()

tool_name = str(payload.get("tool_name", ""))
tool_input = payload.get("tool_input", {}) or {}

is_write_tool = bool(re.search(r"create|write|edit|replace|delete|rename|apply_patch", tool_name, re.I))
is_shell_tool = bool(re.search(r"terminal|bash|shell|exec", tool_name, re.I))

# --- Guard 1: layers/ is kas-managed; never hand-edited ---------------------
if is_write_tool:
    paths = [p.replace("\\", "/") for p in find_paths(tool_input)]
    if any(re.search(r"(^|/)layers/", p) for p in paths):
        decide(
            "deny",
            "layers/ is the kas checkout tree (poky, meta-openembedded, meta-tegra, "
            "meta-swupdate, meta-arches). It is regenerated by kas and never hand-edited "
            "or patched directly — customize meta/meta-arches instead. "
            "See the meta-arches-rules skill.",
        )

# --- Guard 2: dangerous shell commands --------------------------------------
if is_shell_tool:
    command = str(tool_input.get("command", ""))

    deny_patterns = [
        (r"\bgit\s+submodule\s+add\b",
         "submodules are forbidden in this repo (CLAUDE.md) — kas manages layers/ instead"),
        (r"\brm\s+-rf\s+/(\s|/|$)",
         "refusing to remove the filesystem root"),
    ]
    ask_patterns = [
        (r"\bgit\s+push\b[^\n]*(--force\b|-f\b)",
         "force-push rewrites shared history; confirm with the user first"),
        (r"\bgit\s+reset\s+--hard\b",
         "git reset --hard discards local changes; confirm with the user first"),
        (r"\bgit\s+branch\s+-D\b",
         "force-deleting a branch; confirm with the user first"),
        (r"\bbitbake\b[^\n]*-c\s*cleanall\b",
         "bitbake -c cleanall deletes downloaded source; confirm before running"),
        (r"\bmake\s+clean-all\b",
         "make clean-all removes caches + deploy/; confirm before running"),
        (r"\brm\s+-rf\b",
         "rm -rf is destructive; confirm the exact scope with the user first"),
    ]

    for pattern, reason in deny_patterns:
        if re.search(pattern, command):
            decide("deny", reason)
    for pattern, reason in ask_patterns:
        if re.search(pattern, command):
            decide("ask", reason)

allow()
